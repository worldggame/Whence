// Helper to get daily 10 default figures, optionally seeded by calendar date (YYYY-MM-DD)
export function getDailyPack(dateKey?: string): HistoricalFigure[] {
  // If dateKey is provided, compute a deterministic daily rotation across the catalog
  if (dateKey) {
    let hash = 0;
    for (let i = 0; i < dateKey.length; i++) {
      hash = (hash << 5) - hash + dateKey.charCodeAt(i);
      hash |= 0;
    }
    const offset = Math.abs(hash) % DEFAULT_FIGURES.length;
    const shuffled: HistoricalFigure[] = [];
    for (let i = 0; i < 10; i++) {
      shuffled.push(DEFAULT_FIGURES[(offset + i) % DEFAULT_FIGURES.length]);
    }
    return shuffled;
  }

  // Default: first 10 balanced figures
  return DEFAULT_FIGURES.slice(0, 10);
}
